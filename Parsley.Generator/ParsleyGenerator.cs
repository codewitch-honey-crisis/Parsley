#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;

using LexGen;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Parsley.Generator
{
    /// <summary>
    /// Synthesizes a parser, lexer and (with semantic actions) evaluator into a partial class marked
    /// <c>[Parsley("grammar.xbnf")]</c>, with the shared runtime generated once per project unless
    /// Parsley.Runtime.dll is referenced
    /// </summary>
    [Microsoft.CodeAnalysis.Generator(LanguageNames.CSharp)]
    public sealed class ParsleyGenerator : IIncrementalGenerator
    {
        const string AttributeMetadataName = "Parsley.ParserAttribute";
        const string RuntimeAssemblyName = "Parsley.Runtime";
        const string ParserName = "Parser";
        const string LexerName = "Lexer";
        const string EvaluatorName = "Evaluator";

        const string AttributeSource = """
            // <auto-generated/>
            #nullable enable
            namespace Parsley
            {
                /// <summary>
                /// The parsing engine a <see cref="ParserAttribute"/> parser is synthesized for
                /// </summary>
                internal enum ParserEngine
                {
                    /// <summary>The lightest the grammar allows: LL1, then LLk, then AllStar</summary>
                    Auto,
                    /// <summary>One token of lookahead everywhere</summary>
                    LL1,
                    /// <summary>A fixed number of tokens of lookahead, decided at synthesis time</summary>
                    LLk,
                    /// <summary>Adaptive prediction at parse time where one token isn't enough</summary>
                    AllStar
                }

                /// <summary>
                /// Synthesizes a parser for an XBNF grammar into this partial class: a nested Parser, Lexer and, when the
                /// grammar has semantic actions, Evaluator, with public static Parse, TryParse, Tokenize and Evaluate methods
                /// and the parser's symbol constants on this class. The grammar's @class, @evaluator and @lexer directives
                /// are ignored, with a warning: this class decides the names and the namespace, and the lexers are
                /// generated in it.
                /// </summary>
                [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
                [global::System.Diagnostics.Conditional("PARSLEY_GENERATOR_KEEP_ATTRIBUTES")]
                internal sealed class ParserAttribute : global::System.Attribute
                {
                    /// <param name="grammarFile">The XBNF grammar, relative to the source file this attribute is in</param>
                    public ParserAttribute(string grammarFile) { GrammarFile = grammarFile; }
                    /// <summary>
                    /// The XBNF grammar, relative to the source file this attribute is in. It has to be one of the
                    /// project's AdditionalFiles, which every .xbnf file is unless ParsleyIncludeXbnf is false.
                    /// </summary>
                    public string GrammarFile { get; }
                    /// <summary>
                    /// Use Unicode character classes in the lexer. Defaults to false.
                    /// </summary>
                    public bool UseUnicode { get; set; }
                    /// <summary>
                    /// Generate the lexer, Tokenize, and the Parse overloads that take text. Defaults to true. When false,
                    /// only Parse and TryParse over tokens are generated, for tokens from a lexer of your own, and the
                    /// lexer runtime isn't generated unless another parser in the project needs it. It doesn't apply to
                    /// a grammar with islands or terminals from other lexers, which always gets all its lexers: false is
                    /// ignored there, with a warning.
                    /// </summary>
                    public bool HasLexer { get; set; } = true;
                    /// <summary>
                    /// Write #line directives that map the code copied from the grammar (semantic actions, type and state
                    /// attributes, @using) back to it, so compiler errors and the debugger go to the grammar. Defaults to
                    /// true.
                    /// </summary>
                    public bool HasLinePragmas { get; set; } = true;
                    /// <summary>
                    /// The parsing engine. Defaults to the lightest the grammar allows.
                    /// </summary>
                    public ParserEngine Engine { get; set; }
                }
            }
            """;

        static readonly DiagnosticDescriptor s_grammarNotFound = new(
            "PARSLEY001", "Grammar file not found",
            "The grammar file \"{0}\" isn't among the project's AdditionalFiles. Paths are relative to the source file with the [Parsley] attribute; every .xbnf file is included unless ParsleyIncludeXbnf is false, otherwise add <AdditionalFiles Include=\"...\" />.",
            "Parsley", DiagnosticSeverity.Error, true);
        static readonly DiagnosticDescriptor s_grammarAmbiguous = new(
            "PARSLEY002", "Grammar file is ambiguous",
            "More than one of the project's AdditionalFiles ends with \"{0}\": {1}. Give its path relative to the source file with the [Parsley] attribute.",
            "Parsley", DiagnosticSeverity.Error, true);
        static readonly DiagnosticDescriptor s_notPartial = new(
            "PARSLEY003", "Class must be partial",
            "{0} must be partial, as must any type it's nested in, for Parsley to generate into it",
            "Parsley", DiagnosticSeverity.Error, true);
        static readonly DiagnosticDescriptor s_grammarError = new(
            "PARSLEY004", "Grammar error", "{0}", "Parsley", DiagnosticSeverity.Error, true);
        static readonly DiagnosticDescriptor s_grammarWarning = new(
            "PARSLEY005", "Grammar warning", "{0}", "Parsley", DiagnosticSeverity.Warning, true);
        static readonly DiagnosticDescriptor s_grammarMessage = new(
            "PARSLEY006", "Grammar message", "{0}", "Parsley", DiagnosticSeverity.Info, true);
        static readonly DiagnosticDescriptor s_failed = new(
            "PARSLEY007", "Parser generation failed", "Parsley couldn't generate {0}: {1}", "Parsley", DiagnosticSeverity.Error, true);
        static readonly DiagnosticDescriptor s_noGrammar = new(
            "PARSLEY008", "No grammar file given", "The [Parsley] attribute needs the path to an XBNF grammar file", "Parsley", DiagnosticSeverity.Error, true);
        static readonly DiagnosticDescriptor s_lexerNeeded = new(
            "PARSLEY009", "HasLexer is ignored",
            "HasLexer = false is ignored for {0}: its grammar has islands or terminals from other lexers, which are lexed through its own lexer, so all of its lexers are generated",
            "Parsley", DiagnosticSeverity.Warning, true);

        static readonly Dictionary<string, DiagnosticDescriptor> s_descriptors = new[]
        {
            s_grammarNotFound, s_grammarAmbiguous, s_notPartial, s_grammarError, s_grammarWarning, s_grammarMessage, s_failed, s_noGrammar, s_lexerNeeded
        }.ToDictionary(d => d.Id);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(ctx => ctx.AddSource("ParserAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

            var classes = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeMetadataName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, ct) => _GetClassInfo(ctx, ct));

            var grammars = context.AdditionalTextsProvider
                .Where(static t => t.Path.EndsWith(".xbnf", StringComparison.OrdinalIgnoreCase))
                .Select(static (t, ct) => new GrammarFileInfo(_NormalizePath(t.Path), t.GetText(ct)?.ToString() ?? ""))
                .Collect()
                .Select(static (files, _) => new EquatableArray<GrammarFileInfo>(files
                    // the same file listed twice is read once
                    .GroupBy(f => f.Path, StringComparer.OrdinalIgnoreCase).Select(g => g.First())
                    .OrderBy(f => f.Path, StringComparer.Ordinal)));

            var parsers = classes.Combine(grammars).Select(static (pair, ct) => _Generate(pair.Left, pair.Right, ct));

            context.RegisterSourceOutput(parsers, static (spc, parser) =>
            {
                foreach (var d in parser.Diagnostics) spc.ReportDiagnostic(_ToDiagnostic(d));
                if (null != parser.Source)
                    spc.AddSource(parser.HintName, SourceText.From(parser.Source, Encoding.UTF8));
            });

            // the runtime: once per project, for the engines the parsers use, unless Parsley.Runtime.dll supplies it
            var hasRuntimeAssembly = context.CompilationProvider.Select(static (c, _) =>
                c.ReferencedAssemblyNames.Any(a => string.Equals(a.Name, RuntimeAssemblyName, StringComparison.OrdinalIgnoreCase)));
            var generated = parsers.Where(static p => 0 < p.Engines.Count);
            var engines = generated
                .Select(static (p, _) => p.Engines)
                .Collect()
                .Select(static (es, _) => new EquatableArray<int>(es.SelectMany(e => e).Distinct().OrderBy(e => e)));
            // the lexer runtime only when some parser has a lexer
            var anyLexer = generated
                .Select(static (p, _) => p.HasLexer)
                .Collect()
                .Select(static (ls, _) => ls.Any(l => l));
            context.RegisterSourceOutput(engines.Combine(anyLexer).Combine(hasRuntimeAssembly), static (spc, pair) =>
            {
                var ((used, lexers), hasRuntime) = pair;
                if (hasRuntime || 0 == used.Count) return;
                spc.AddSource("Parsley.Runtime.ParsleyRuntime.g.cs", SourceText.From(_Generated(CSharpSynthesizer.RuntimeSource), Encoding.UTF8));
                foreach (var e in used)
                {
                    var engine = (ParserEngine)e;
                    spc.AddSource($"Parsley.Runtime.{engine.BaseClassName()}.g.cs", SourceText.From(_Generated(CSharpSynthesizer.BaseSource(engine)), Encoding.UTF8));
                }
                // the lexer runtime goes in Parsley.Runtime with the rest: generated lexers call it there, as they
                // call Parsley.Runtime.dll's when the project references that
                if (lexers)
                    spc.AddSource("Parsley.Runtime.LuthorRuntime.g.cs", SourceText.From(_Generated(LexerEmitter.RuntimeSourceIn("Parsley.Runtime")), Encoding.UTF8));
            });
        }

        // marks a runtime source as generated, so analyzers and style rules leave it alone
        static string _Generated(string source) => "// <auto-generated/>\r\n" + source;

        #region Reading the class
        static ParserClassInfo _GetClassInfo(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
        {
            var symbol = (INamedTypeSymbol)ctx.TargetSymbol;
            var node = (ClassDeclarationSyntax)ctx.TargetNode;
            var attr = ctx.Attributes[0];
            var diagnostics = new List<DiagnosticInfo>();
            var attrLocation = LocationInfo.From(attr.ApplicationSyntaxReference?.GetSyntax(ct).GetLocation()) ?? LocationInfo.From(node.Identifier.GetLocation());

            string? grammarFile = null;
            if (1 == attr.ConstructorArguments.Length && attr.ConstructorArguments[0].Value is string s && 0 < s.Trim().Length)
                grammarFile = s.Trim();
            var useUnicode = false;
            var hasLexer = true;
            var hasLinePragmas = true;
            var engine = 0;
            foreach (var arg in attr.NamedArguments)
            {
                switch (arg.Key)
                {
                    case "UseUnicode": useUnicode = arg.Value.Value is bool u && u; break;
                    case "HasLexer": hasLexer = arg.Value.Value is not bool l || l; break;
                    case "HasLinePragmas": hasLinePragmas = arg.Value.Value is not bool lp || lp; break;
                    case "Engine": engine = arg.Value.Value is int e ? e : 0; break;
                }
            }
            if (null == grammarFile)
                diagnostics.Add(new DiagnosticInfo(s_noGrammar.Id, s_noGrammar.DefaultSeverity, s_noGrammar.MessageFormat.ToString(), attrLocation));

            // the class and every type it's nested in, outermost first
            var types = new List<TypeDeclarationInfo>();
            for (SyntaxNode? n = node; null != n; n = n.Parent)
            {
                if (n is not TypeDeclarationSyntax t) continue;
                if (!t.Modifiers.Any(SyntaxKind.PartialKeyword))
                {
                    var msg = string.Format(s_notPartial.MessageFormat.ToString(), t.Identifier.ValueText);
                    diagnostics.Add(new DiagnosticInfo(s_notPartial.Id, s_notPartial.DefaultSeverity, msg, LocationInfo.From(t.Identifier.GetLocation())));
                }
                var keyword = t is RecordDeclarationSyntax r
                    ? (r.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword) ? "record struct" : "record")
                    : t.Keyword.ValueText;
                types.Insert(0, new TypeDeclarationInfo(keyword, t.Identifier.ValueText, t.TypeParameterList?.ToString() ?? ""));
            }

            var ns = symbol.ContainingNamespace is { IsGlobalNamespace: false } cn ? cn.ToDisplayString() : null;
            // the class's full name, with each generic type's arity, is unique in the project
            var hint = (null != ns ? ns + "." : "") + string.Join(".", _Containing(symbol).Select(t => t.Name + (0 < t.Arity ? "`" + t.Arity.ToString() : "")));
            return new ParserClassInfo(
                hint + ".Parsley.g.cs",
                ns,
                new EquatableArray<TypeDeclarationInfo>(types),
                node.SyntaxTree.FilePath,
                grammarFile,
                useUnicode,
                hasLexer,
                hasLinePragmas,
                engine,
                new EquatableArray<string>(symbol.MemberNames.Distinct().OrderBy(m => m, StringComparer.Ordinal)),
                attrLocation,
                new EquatableArray<DiagnosticInfo>(diagnostics));
        }
        static IEnumerable<INamedTypeSymbol> _Containing(INamedTypeSymbol symbol)
        {
            var list = new List<INamedTypeSymbol>();
            for (var t = symbol; null != t; t = t.ContainingType) list.Insert(0, t);
            return list;
        }
        #endregion

        #region Generating
        static GeneratedParser _Generate(ParserClassInfo info, EquatableArray<GrammarFileInfo> grammars, CancellationToken ct)
        {
            var diagnostics = new List<DiagnosticInfo>(info.Diagnostics);
            GeneratedParser failed() => new GeneratedParser(info.HintName, null, EquatableArray<int>.Empty, false, new EquatableArray<DiagnosticInfo>(diagnostics));
            if (diagnostics.Any(d => d.Severity == DiagnosticSeverity.Error) || null == info.GrammarFile)
                return failed();

            var grammarFile = _FindGrammar(info, grammars, diagnostics);
            if (null == grammarFile) return failed();
            ct.ThrowIfCancellationRequested();

            var className = info.Types[info.Types.Count - 1].Name;
            try
            {
                // imports are read from the AdditionalFiles too, never from disk
                var byPath = grammars.ToDictionary(g => g.Path, g => g.Text, StringComparer.OrdinalIgnoreCase);
                string readImport(string path) => byPath.TryGetValue(_NormalizePath(path), out var text)
                    ? text
                    : throw new FileNotFoundException($"{Path.GetFileName(path)} isn't among the project's AdditionalFiles");

                var messages = XbnfParser.TryParse(grammarFile.Text, grammarFile.Path, readImport, out var grammar);
                _AddMessages(messages, info, diagnostics);
                if (null == grammar || messages.Any(m => m.Level == ErrorLevel.Error)) return failed();
                ct.ThrowIfCancellationRequested();

                var analysis = GrammarAnalysis.Analyze(grammar, (ParserEngine)info.Engine);
                _AddMessages(analysis.Messages, info, diagnostics);
                if (analysis.HasErrors) return failed();
                ct.ThrowIfCancellationRequested();

                // the nested classes' declarations are indented one past the class's, which is inside its namespace and containing types
                var depth = info.Types.Count + (null != info.Namespace ? 1 : 0);
                // members of the class this generates, and those it already has, aren't symbol constant names
                var reserved = new HashSet<string>(info.MemberNames)
                {
                    className, ParserName, LexerName, EvaluatorName, "Parse", "TryParse", "Tokenize", "Evaluate", "SymbolCount", "CreateLexerMode"
                };
                // the class decides the names and the namespace, and the lexers are generated in it
                _WarnIgnored(grammar, null, info, diagnostics);
                // a compound grammar is lexed through its own lexer, so it always gets all its lexers
                var lexer = info.HasLexer;
                if (!lexer && analysis.Grammar.IsCompound)
                {
                    diagnostics.Add(new DiagnosticInfo(s_lexerNeeded.Id, s_lexerNeeded.DefaultSeverity,
                        string.Format(s_lexerNeeded.MessageFormat.ToString(), className), info.AttributeLocation));
                    lexer = true;
                }
                // no access: the nested classes are partial and private, unless another part of one gives it an access
                var unit = _Synthesize(analysis, depth, lexer, reserved, "", info, diagnostics, ct);
                if (null == unit) return failed();

                var source = _Write(info, grammarFile, unit);
                return new GeneratedParser(info.HintName, source, new EquatableArray<int>(unit.Engines.OrderBy(e => e)), unit.HasLexer, new EquatableArray<DiagnosticInfo>(diagnostics));
            }
            catch (OperationCanceledException)
            {
                throw;
            }
            catch (GrammarException ex)
            {
                _AddMessages(ex.Messages, info, diagnostics);
                if (!diagnostics.Any(d => d.Severity == DiagnosticSeverity.Error))
                    diagnostics.Add(_Failed(className, ex.Message, info));
                return failed();
            }
            catch (Exception ex)
            {
                diagnostics.Add(_Failed(className, ex.Message, info));
                return failed();
            }
        }

        // a grammar synthesized into nested classes: its parser and evaluator, its lexers, and a class for each
        // @external grammar holding the same for it
        sealed class _Unit
        {
            public _Unit(SynthesizedParser parser, string code, string? ownLexer)
            {
                Parser = parser;
                Code = code;
                OwnLexer = ownLexer;
            }
            public SynthesizedParser Parser { get; }
            // the nested classes, indented: the parser, lexers, evaluator and external grammars' classes
            public string Code { get; }
            // the type whose Tokenize lexes the grammar itself, or null if it has none
            public string? OwnLexer { get; }
            public HashSet<int> Engines { get; } = new HashSet<int>();
            public bool HasLexer { get; set; }
        }

        // a lexer of the terminals, nested, in the order the parser numbers them
        static string _Lexer(IEnumerable<TerminalDeclaration> terminals, string name, string access, bool unicode, int depth)
        {
            var rules = terminals
                .Select(t => new Rule(t.Name, t.Regex ?? throw new InvalidOperationException($"The terminal {t.Name} has no pattern"), t.IsHidden))
                .ToList();
            var writer = new StringWriter();
            LexerEmitter.Emit(rules, writer, new LexerEmitOptions
            {
                ClassName = name,
                Access = access,
                Partial = true,
                Unicode = unicode,
                Nested = true,
                Indent = new string('\t', depth),
                RuntimeNamespace = "Parsley.Runtime",
            });
            return writer.ToString();
        }

        // synthesizes a grammar into nested classes at the given depth. @class, @evaluator and @lexer are ignored, with
        // a warning (see _WarnIgnored): the names are fixed, the containing class decides the namespace, and every
        // lexer is generated. An @external grammar's parser and lexer go in a class named after its alias, so a
        // grammar and the grammars it embeds come from the one [Parser] attribute.
        static _Unit? _Synthesize(GrammarAnalysis analysis, int depth, bool lexer, HashSet<string> reserved, string access,
            ParserClassInfo info, List<DiagnosticInfo> diagnostics, CancellationToken ct)
        {
            var g = analysis.Grammar;
            var unicode = info.UseUnicode;
            var ownLexer = lexer ? LexerName : null;
            var groupLexers = g.LexerGroups.ToDictionary(a => a, a => a + LexerName);
            var externals = g.Externals.Where(x => null != x.Grammar).ToList();
            var names = new HashSet<string>(reserved);
            foreach (var x in externals) names.Add(x.Alias);
            foreach (var l in groupLexers.Values) names.Add(l);
            // the containing class gets a TryParseXxx for each shared production, named as the parser's are
            var methods = MethodNames.For(g);
            foreach (var p in g.SharedProductions) names.Add(methods.TryParse(p.Name));
            var parser = CSharpSynthesizer.SynthesizeParser(analysis, new SynthesisOptions
            {
                ClassName = ParserName,
                EvaluatorClassName = EvaluatorName,
                Nested = true,
                NestedAccess = access,
                Indent = depth,
                ReservedNames = names,
                LexerType = alias => null == alias ? ownLexer ?? LexerName : groupLexers.TryGetValue(alias, out var gl) ? gl : $"{alias}.{LexerName}",
                ExternalParser = alias => $"{alias}.{ParserName}",
                // no #line directives at all when the attribute says so
                LinePath = info.HasLinePragmas ? null : _ => "",
            });
            // a symbol constant renamed to stay clear of a member or a name the code uses
            _AddMessages(parser.Messages, info, diagnostics);
            ct.ThrowIfCancellationRequested();
            var code = new StringBuilder(parser.Code);
            var engines = new HashSet<int> { (int)parser.Engine };
            var hasLexer = false;
            // the grammar's own lexer: the terminals it lexes itself, not contextual ones, islands, or those from other lexers
            if (lexer)
            {
                code.Append("\r\n").Append(_Lexer(g.Terminals.Where(t => t.IsLexed), LexerName, access, unicode, depth));
                hasLexer = true;
            }
            // a lexer for each lexer=
            foreach (var alias in g.LexerGroups)
            {
                code.Append("\r\n").Append(_Lexer(g.Terminals.Where(t => t.Lexer == alias && !t.IsIsland), groupLexers[alias], access, unicode, depth));
                hasLexer = true;
            }
            // each external grammar: a class named after its alias, holding its parser, lexer and evaluator
            foreach (var x in externals)
            {
                var inner = GrammarAnalysis.Analyze(x.Grammar!);
                _AddMessages(inner.Messages.Where(m => ErrorLevel.Error == m.Level), info, diagnostics);
                if (inner.HasErrors) return null;
                // its @class, @evaluator and @lexer are no more honored than the grammar's own
                _WarnIgnored(x.Grammar!, x.Alias, info, diagnostics);
                var innerReserved = new HashSet<string> { x.Alias, ParserName, LexerName, EvaluatorName, "Evaluate", "SymbolCount" };
                // reached from the outer parser, so internal rather than private
                const string innerAccess = "internal";
                var innerUnit = _Synthesize(inner, depth + 1, true, innerReserved, innerAccess, info, diagnostics, ct);
                if (null == innerUnit) return null;
                engines.UnionWith(innerUnit.Engines);
                hasLexer |= innerUnit.HasLexer;
                // internal, so code anywhere in the project can read the island grammar's symbol constants
                code.Append("\r\n").Append(_Container(x, innerUnit, depth, innerAccess));
            }
            var result = new _Unit(parser, code.ToString(), ownLexer) { HasLexer = hasLexer };
            result.Engines.UnionWith(engines);
            return result;
        }

        // the directives the generator doesn't honor, each with a warning where it's written: the class with the
        // attribute decides the parser's name and namespace, the evaluator is always the nested Evaluator, and every
        // lexer is generated nested in the class. alias is the @external grammar's, or null for the grammar itself.
        static void _WarnIgnored(Grammar g, string? alias, ParserClassInfo info, List<DiagnosticInfo> diagnostics)
        {
            var messages = new List<GrammarMessage>();
            var whose = null == alias ? "" : $" (in the @external grammar {alias})";
            GrammarMessage at(string directive, string message) => g.DirectiveLocations.TryGetValue(directive, out var node)
                ? new GrammarMessage(ErrorLevel.Warning, message, node)
                : new GrammarMessage(ErrorLevel.Warning, message, 0, 0, -1, g.Filename);
            if (g.Directives.TryGetValue("class", out var c))
                messages.Add(at("class", $"@class \"{c}\"{whose} is ignored by the source generator: the class with the [Parser] attribute decides the parser's name and namespace"));
            if (g.Directives.TryGetValue("evaluator", out var e))
                messages.Add(at("evaluator", $"@evaluator \"{e}\"{whose} is ignored by the source generator: the evaluator is the nested {EvaluatorName} class"));
            foreach (var l in g.Lexers)
            {
                var which = null == l.Alias ? "@lexer" : $"@lexer {l.Alias}";
                messages.Add(new GrammarMessage(ErrorLevel.Warning, $"{which} \"{l.TypeName}\"{whose} is ignored by the source generator: its lexers are generated, nested in the class with the [Parser] attribute", l));
            }
            _AddMessages(messages, info, diagnostics);
        }

        // the class an external grammar's nested classes go in, named after its alias, with its symbol constants
        static string _Container(ExternalGrammar x, _Unit unit, int depth, string access)
        {
            var sb = new StringBuilder();
            var ind = new string('\t', depth);
            void line(string text = "") => sb.Append(0 < text.Length ? ind + text : "").Append("\r\n");
            line($"/// <summary>");
            line($"/// The @external grammar {x.Alias}, from {Path.GetFileName(x.Path)}: the parser, lexer and evaluator for its islands");
            line($"/// </summary>");
            line($"{(0 < access.Length ? access + " " : "")}static partial class {x.Alias}");
            line("{");
            ind += "\t";
            line("#region Symbols");
            foreach (var c in unit.Parser.Constants)
                line($"public const int {c.Name} = {c.Id};{(null != c.Comment ? " // " + c.Comment : "")}");
            line($"public const int SymbolCount = {unit.Parser.Constants.Count};");
            line("#endregion");
            if (null != unit.Parser.EvaluatorClassName)
            {
                line();
                line("/// <summary>");
                line($"/// Evaluates a tree of {x.Alias}'s, such as an island's, with its semantic actions");
                line("/// </summary>");
                // mapped to the grammar's type or state attribute, which it names
                if (null != unit.Parser.EvaluateLineDirective) sb.Append(unit.Parser.EvaluateLineDirective).Append("\r\n");
                line($"public static {unit.Parser.EvaluateReturnType} Evaluate(global::Parsley.Runtime.ParseNode node, {unit.Parser.EvaluateStateParameter}) => {unit.Parser.EvaluatorClassName}.Evaluate(node, state);");
                if (null != unit.Parser.EvaluateLineDirective) sb.Append("#line default\r\n");
            }
            line();
            sb.Append(unit.Code.Replace("\r\n", "\n").Replace("\n", "\r\n"));
            ind = ind.Substring(1);
            line("}");
            return sb.ToString();
        }

        static DiagnosticInfo _Failed(string className, string message, ParserClassInfo info)
            => new DiagnosticInfo(s_failed.Id, s_failed.DefaultSeverity, string.Format(s_failed.MessageFormat.ToString(), className, message), info.AttributeLocation);

        // the grammar file: relative to the source file with the attribute, else the one AdditionalFile whose path ends with it
        static GrammarFileInfo? _FindGrammar(ParserClassInfo info, EquatableArray<GrammarFileInfo> grammars, List<DiagnosticInfo> diagnostics)
        {
            var given = info.GrammarFile!;
            string? full = null;
            try
            {
                var dir = 0 < info.SourceFilePath.Length ? Path.GetDirectoryName(info.SourceFilePath) : null;
                full = Path.IsPathRooted(given) ? _NormalizePath(given)
                    : null != dir && 0 < dir.Length ? _NormalizePath(Path.Combine(dir, given)) : null;
            }
            catch (ArgumentException)
            {
                // an invalid path is matched by its ending below, and reported as not found
            }
            if (null != full)
                foreach (var g in grammars)
                    if (string.Equals(g.Path, full, StringComparison.OrdinalIgnoreCase))
                        return g;

            var suffix = given.Replace('\\', '/').TrimStart('.', '/');
            var matches = grammars.Where(g =>
            {
                var p = g.Path.Replace('\\', '/');
                return p.EndsWith("/" + suffix, StringComparison.OrdinalIgnoreCase) || string.Equals(p, suffix, StringComparison.OrdinalIgnoreCase);
            }).ToList();
            if (1 == matches.Count) return matches[0];
            if (0 == matches.Count)
                diagnostics.Add(new DiagnosticInfo(s_grammarNotFound.Id, s_grammarNotFound.DefaultSeverity,
                    string.Format(s_grammarNotFound.MessageFormat.ToString(), given), info.AttributeLocation));
            else
                diagnostics.Add(new DiagnosticInfo(s_grammarAmbiguous.Id, s_grammarAmbiguous.DefaultSeverity,
                    string.Format(s_grammarAmbiguous.MessageFormat.ToString(), given, string.Join(", ", matches.Select(m => m.Path))), info.AttributeLocation));
            return null;
        }

        static string _NormalizePath(string path)
        {
            try
            {
                return Path.GetFullPath(path);
            }
            catch (Exception)
            {
                return path;
            }
        }

        // grammar messages are reported where they are in the grammar, or on the attribute when they have no location
        static void _AddMessages(IEnumerable<GrammarMessage> messages, ParserClassInfo info, List<DiagnosticInfo> diagnostics)
        {
            foreach (var m in messages)
            {
                var descriptor = m.Level switch
                {
                    ErrorLevel.Error => s_grammarError,
                    ErrorLevel.Warning => s_grammarWarning,
                    _ => s_grammarMessage,
                };
                LocationInfo? location = info.AttributeLocation;
                if (null != m.Filename && 0 < m.Line)
                {
                    var pos = new LinePosition(m.Line - 1, Math.Max(0, m.Column - 1));
                    location = new LocationInfo(_NormalizePath(m.Filename), new TextSpan((int)Math.Max(0, m.Position), 0), new LinePositionSpan(pos, pos));
                }
                var d = new DiagnosticInfo(descriptor.Id, descriptor.DefaultSeverity, m.Message, location);
                if (!diagnostics.Contains(d)) diagnostics.Add(d);
            }
        }

        static Diagnostic _ToDiagnostic(DiagnosticInfo d)
        {
            // the descriptor's format is "{0}" for grammar messages; the others are already formatted
            var descriptor = s_descriptors[d.Id];
            var passthrough = new DiagnosticDescriptor(descriptor.Id, descriptor.Title, "{0}", descriptor.Category, descriptor.DefaultSeverity, descriptor.IsEnabledByDefault);
            return Diagnostic.Create(passthrough, d.Location?.ToLocation() ?? Location.None, d.Message);
        }

        // the partial class: the parser's constants and static entry points, then the nested Parser, Evaluator and,
        // unless it's null, Lexer
        static string _Write(ParserClassInfo info, GrammarFileInfo grammar, _Unit unit)
        {
            var parser = unit.Parser;
            var sb = new StringBuilder();
            var indent = 0;
            void line(string text = "")
            {
                if (0 < text.Length) sb.Append('\t', indent);
                sb.Append(text).Append("\r\n");
            }
            void open(string text) { line(text); line("{"); ++indent; }
            void close() { --indent; line("}"); }

            line("// <auto-generated>");
            line($"// Synthesized by Parsley.Generator from {Path.GetFileName(grammar.Path)}. Changes are lost when it is synthesized again;");
            line("// add members in another part of this partial class instead.");
            line("// </auto-generated>");
            line("#nullable enable");
            // with #line directives mapping those from @using to the grammar
            foreach (var u in parser.UsingLines)
                line(u);
            line();
            if (null != info.Namespace) open($"namespace {info.Namespace}");
            for (var i = 0; i < info.Types.Count - 1; ++i)
            {
                var t = info.Types[i];
                open($"partial {t.Keyword} {t.Name}{t.TypeParameters}");
            }
            var self = info.Types[info.Types.Count - 1];
            open($"partial {self.Keyword} {self.Name}{self.TypeParameters}");

            line("#region Symbols");
            foreach (var c in parser.Constants)
                line($"public const int {c.Name} = {c.Id};{(null != c.Comment ? " // " + c.Comment : "")}");
            line($"public const int SymbolCount = {parser.Constants.Count};");
            line("#endregion");
            line();

            const string token = "global::Parsley.Runtime.Token";
            const string tokens = "global::System.Collections.Generic.IEnumerable<" + token + ">";
            const string node = "global::Parsley.Runtime.ParseNode";
            const string errorList = "global::System.Collections.Generic.IReadOnlyList<global::Parsley.Runtime.ParseError>";
            const string lexArgs = "long position = 0, int line = 1, int column = 1, int tabWidth = 4";
            const string lexPass = "position, line, column, tabWidth";
            var lexer = unit.OwnLexer;
            if (null != lexer)
            {
                // a compound grammar lexes through a controller, which switches to its islands' and other lexers
                string from(string source) => parser.IsCompound
                    ? $"new global::Parsley.Runtime.LexerController({ParserName}.CreateLexerMode({lexer}.Tokenize), {source}, {lexPass})"
                    : $"{lexer}.Tokenize({source}, {lexPass})";
                var what = parser.IsCompound ? "Splits text into tokens for Parse, lexing each island with its own grammar's lexer. Hidden terminals are skipped." : "Splits text into tokens for Parse. Hidden terminals are skipped.";
                line("/// <summary>");
                line($"/// {what}");
                line("/// </summary>");
                line($"public static {tokens} Tokenize(string text, {lexArgs}) => {from("text")};");
                line("/// <summary>");
                line($"/// {what}");
                line("/// </summary>");
                line($"public static {tokens} Tokenize(global::System.IO.TextReader reader, {lexArgs}) => {from("reader")};");
                line();
            }
            if (!parser.IsSubordinate)
            {
                line("/// <summary>");
                line("/// Parses tokens, returning the tree and the problems found, if any. Returns false when there were problems.");
                line("/// </summary>");
                line($"public static bool TryParse({tokens} tokens, out {node} result, out {errorList} errors) => {ParserName}.TryParse(tokens, out result, out errors);");
                line("/// <summary>");
                line("/// Parses tokens and returns the tree. Throws a ParseException with every problem found if there were any.");
                line("/// </summary>");
                line($"public static {node} Parse({tokens} tokens) => {ParserName}.Parse(tokens);");
                if (null != lexer)
                {
                    line("/// <summary>");
                    line("/// Tokenizes and parses text, and returns the tree. Throws a ParseException with every problem found if there were any.");
                    line("/// </summary>");
                    line($"public static {node} Parse(string text) => {ParserName}.Parse(Tokenize(text));");
                    line("/// <summary>");
                    line("/// Tokenizes and parses what a reader reads, and returns the tree. Throws a ParseException with every problem found if there were any.");
                    line("/// </summary>");
                    line($"public static {node} Parse(global::System.IO.TextReader reader) => {ParserName}.Parse(Tokenize(reader));");
                }
            }
            // the shared productions, which other grammars parse islands with
            foreach (var entry in parser.SharedEntries)
            {
                line("/// <summary>");
                line($"/// Parses one {entry.Substring(MethodNames.TryParsePrefix.Length)} from tokens, as an island of another grammar. Returns false when there were problems.");
                line("/// </summary>");
                line($"public static bool {entry}({tokens} tokens, out {node} result, out {errorList} errors) => {ParserName}.{entry}(tokens, out result, out errors);");
            }
            if (parser.HasLexerMode)
            {
                line("/// <summary>");
                line("/// How a LexerController lexes this grammar with the given lexer: its islands and the terminals other lexers produce");
                line("/// </summary>");
                line($"public static global::Parsley.Runtime.LexerMode CreateLexerMode(global::Parsley.Runtime.TokenizeFunc tokenize) => {ParserName}.CreateLexerMode(tokenize);");
            }
            if (null != parser.EvaluatorClassName)
            {
                line();
                line("/// <summary>");
                line("/// Evaluates a parse tree with the grammar's semantic actions");
                line("/// </summary>");
                line("/// <param name=\"node\">The root of the tree</param>");
                line("/// <param name=\"state\">Anything the semantic actions need, available to them as State</param>");
                // mapped to the grammar's type or state attribute, which it names
                if (null != parser.EvaluateLineDirective) sb.Append(parser.EvaluateLineDirective).Append("\r\n");
                line($"public static {parser.EvaluateReturnType} Evaluate({node} node, {parser.EvaluateStateParameter}) => {parser.EvaluatorClassName}.Evaluate(node, state);");
                if (null != parser.EvaluateLineDirective) sb.Append("#line default\r\n");
            }
            line();

            // the synthesizer and lexer emitter indent the nested classes themselves
            sb.Append(unit.Code.Replace("\r\n", "\n").Replace("\n", "\r\n"));

            close();
            for (var i = 0; i < info.Types.Count - 1; ++i) close();
            if (null != info.Namespace) close();
            return sb.ToString();
        }
        #endregion
    }
